// Regenerates public/sitemap.xml from siteConfig.siteUrl and current catalogue (PCD families/tools, Applications and News hidden). Run: bun scripts/sitemap.ts
import { writeFileSync } from 'node:fs';
import { siteConfig } from '../src/lib/siteConfig';
import { products } from '../src/data/products';
import { categories } from '../src/pages/productsData';
const file = new URL('../public/sitemap.xml', import.meta.url);
const paths = ['/', '/about', '/products', '/services', '/contact', '/privacy', '/terms', '/products/pcd/pcd-tooling', '/products/pcd/pcd-technology'];
const all = [...new Set([
  ...paths,
  ...categories.flatMap(category => category.id === 'pcd' ? [`/products/${category.id}`] : [
    `/products/${category.id}`,
    ...category.subcategories.map(family => `/products/${category.id}/${family.id}`),
  ]),
  ...products.filter(product => product.category !== 'pcd').map(product => `/products/${product.slug}`),
])];
writeFileSync(file, `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/sitemap.ts. HashRouter fragments are not separately indexable by search engines.
     lastmod is omitted because authoritative page-specific content dates are unavailable. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${all.map(p => `  <url><loc>${siteConfig.siteUrl}/#${p}</loc></url>`).join('\n')}
</urlset>
`);
